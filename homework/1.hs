{-
Задание 3
    Вычисляем предел с заданной точностью 
    заранее зная реальный предел 
    
    eps - заданая точность
-}

{-Решение для 411c-}
-- знаем, что предел этой последовательности равен 0.5

-- check_411c ищет предел с заданной точностью для этого 
-- проверяем выполняется ли условие из определения 
-- предела последовательности: abs(xn - L) < eps 
-- где L - известный нам предел, а eps заданая точность
check_411c n eps = 
    if abs(solve_411c n - 0.5) < eps
        then solve_411c n
        else check_411c (n + 1) eps 

limit_411c eps = 
    check_411c 1 eps 
{-
Проверка работы limit_411c
    ghci> limit_411c 0.01 
    0.5098039215686274

    ghci> limit_411c 0.00001  
    0.500009999800004

    Проверка:
    
    0.5098039215686274 - 0.5 = 
    0.0098039215686274 < 0.01 
    Верно

    0.500009999800004 - 0.5 =
    0.000009999800004 < 0.00001 
    Верно
-}

{-Решение для 411b-}
-- знаем, что предел этой функции при x -> 1 равен 2/3

-- check411b ищет предел с заданой точностью для этого 
-- проверяем выполнется ли условие из определения 
-- предела функции по Коши: abs(f(x) - L) < eps 
-- где L - извесный нам предел, а eps заданая точность
check_411b x eps = 
    if abs (solve_411b (1 - 1 / x) - (2 / 3)) < eps
        then solve_411b (1 - 1 / x)
        else check_411b (x + 1) eps

limit_411b eps =
    check_411b 1 eps
{-
