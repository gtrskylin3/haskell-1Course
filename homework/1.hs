{-
Задание №4
    Автоматически вычисляем предел с заданной точностью 
    не зная реальное значение предела
-}

-- auto_check411c ищет предел с заданой точностью для этого
-- cравниваем два последовательных значения последовательности.
-- Если их разность по модулю меньше eps,
-- считаем, что мы нашли предел с заданой точностью

auto_check411c x eps = 
    if abs (solve_411c (x + 1) - solve_411c x) < eps
        then solve_411c x
        else auto_check411c (x + 1) eps

find_limit411c eps = 
    auto_check411c 1 eps 

